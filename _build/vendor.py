"""
Self-host third-party files so every page loads from one origin (faster on mobile).

Run once (and again whenever a new Bootstrap Icon is used), then rebuild:
    python vendor.py && python build.py

- Copies GSAP, ScrollTrigger, Lenis and Swiper into assets/vendor/
- Downloads the Google Fonts (latin subset only) into assets/fonts/
- Builds a tiny Bootstrap Icons font with only the icons the site uses
- Writes the @font-face + icon rules into the generated block at the end of style.css
"""
import io, os, re, urllib.request
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENDOR = os.path.join(ROOT, 'assets', 'vendor')
FONTS = os.path.join(ROOT, 'assets', 'fonts')
CSS = os.path.join(ROOT, 'assets', 'css', 'style.css')
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36'

LIBS = {
    'gsap.min.js': 'https://cdnjs.cloudflare.com/ajax/libs/gsap/3.12.5/gsap.min.js',
    'ScrollTrigger.min.js': 'https://cdnjs.cloudflare.com/ajax/libs/gsap/3.12.5/ScrollTrigger.min.js',
    'lenis.min.js': 'https://cdn.jsdelivr.net/npm/lenis@1.1.13/dist/lenis.min.js',
    'swiper-bundle.min.js': 'https://cdn.jsdelivr.net/npm/swiper@11.1.14/swiper-bundle.min.js',
    'swiper-bundle.min.css': 'https://cdn.jsdelivr.net/npm/swiper@11.1.14/swiper-bundle.min.css',
}
GOOGLE_FONTS = 'https://fonts.googleapis.com/css2?family=Instrument+Sans:wght@400;500;600&family=Instrument+Serif:ital@0;1&family=Stack+Sans+Headline:wght@500;600;700&display=swap'
BI = 'https://cdn.jsdelivr.net/npm/bootstrap-icons@1.11.3/font/'
START, END = '/* ===== Generated by _build/vendor.py: fonts + icons (do not edit by hand) ===== */', '/* ===== End generated block ===== */'


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=60).read()


def used_icons():
    names = set()
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if not d.startswith('.') and d not in ('vendor', 'img', 'fonts')]
        for f in files:
            if f.endswith(('.html', '.js', '.py')):
                names |= set(re.findall(r'\bbi-[a-z0-9-]+', open(os.path.join(base, f), encoding='utf8', errors='ignore').read()))
    return names


def main():
    os.makedirs(VENDOR, exist_ok=True)
    os.makedirs(FONTS, exist_ok=True)
    for name, url in LIBS.items():
        open(os.path.join(VENDOR, name), 'wb').write(get(url))

    # Google Fonts: keep only the latin subset of each face
    css = get(GOOGLE_FONTS).decode()
    faces, seen = [], {}
    for comment, block in re.findall(r'/\* ([\w-]+) \*/\s*(@font-face \{.*?\})', css, re.S):
        if comment != 'latin':
            continue
        fam = re.search(r"font-family: '([^']+)'", block).group(1)
        style = re.search(r'font-style: (\w+)', block).group(1)
        weight = re.search(r'font-weight: ([\d ]+)', block).group(1).replace(' ', '-')
        url = re.search(r'url\((https://[^)]+)\)', block).group(1)
        # variable fonts: several weights share one file, so download it once
        fname = seen.get(url) or f"{fam.lower().replace(' ', '-')}-{style}.woff2"
        if url not in seen:
            seen[url] = fname
            open(os.path.join(FONTS, fname), 'wb').write(get(url))
        faces.append(block.replace(url, f'../fonts/{fname}'))

    # Bootstrap Icons: subset to the icons in use
    bi_css = get(BI + 'bootstrap-icons.css').decode()
    codes = dict(re.findall(r'\.(bi-[a-z0-9-]+)::before \{ content: "\\([0-9a-f]+)"; \}', bi_css))
    used = sorted(n for n in used_icons() if n in codes)
    font = TTFont(io.BytesIO(get(BI + 'fonts/bootstrap-icons.woff2')))
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = []
    sub = subset.Subsetter(opts)
    # icons drawn straight from style.css (content: "\Fxxx" with the bootstrap-icons font)
    own_css = open(CSS, encoding='utf8').read().split(START)[0]
    css_codes = {int(c, 16) for line in own_css.splitlines() if 'bootstrap-icons' in line for c in re.findall(r'content: "\\([0-9A-Fa-f]{4})"', line)}
    sub.populate(unicodes=[int(codes[n], 16) for n in used] + sorted(css_codes))
    sub.subset(font)
    font.flavor = 'woff2'
    font.save(os.path.join(FONTS, 'bootstrap-icons-subset.woff2'))

    icons = ['@font-face { font-display: block; font-family: "bootstrap-icons"; src: url("../fonts/bootstrap-icons-subset.woff2") format("woff2"); }',
             '.bi::before, [class^="bi-"]::before, [class*=" bi-"]::before { display: inline-block; font-family: bootstrap-icons !important; font-style: normal; font-weight: normal !important; font-variant: normal; text-transform: none; line-height: 1; width: 1em; text-align: center; vertical-align: -.125em; -webkit-font-smoothing: antialiased; -moz-osx-font-smoothing: grayscale; }']
    icons += [f'.{n}::before {{ content: "\\{codes[n]}"; }}' for n in used]

    block = '\n'.join([START] + faces + icons + [END])
    s = open(CSS, encoding='utf8').read()
    s = re.sub(re.escape(START) + r'.*?' + re.escape(END), '', s, flags=re.S).rstrip() + '\n\n' + block + '\n'
    open(CSS, 'w', encoding='utf8').write(s)
    print(f'vendor: {len(LIBS)} libraries, {len(faces)} font files, {len(used)} icons')


if __name__ == '__main__':
    main()
